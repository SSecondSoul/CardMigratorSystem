// Real built frontend against a disposable API seeded with frozen failed jobs.
// No model transport and no writes to the user's service or database.
import {createRequire} from 'node:module'
const require=createRequire(new URL('../../browser/package.json',import.meta.url))
const puppeteer=require('puppeteer-core')
import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
const config=JSON.parse(fs.readFileSync(0,'utf8'))
const browser=await puppeteer.launch({executablePath:config.executable,headless:true})
try {
  fs.mkdirSync(config.output,{recursive:true})
  const page=await browser.newPage(),errors=[],writes=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(r.method()==='POST')writes.push(new URL(r.url()).pathname)})
  await page.setViewport({width:1586,height:1000,deviceScaleFactor:1})
  await page.goto(config.url,{waitUntil:'networkidle0'})
  await page.waitForSelector('.cm-metric-value')
  await page.waitForFunction(()=>document.querySelectorAll('.cm-image-pair img').length===2)
  await page.screenshot({path:path.join(config.output,'desktop.png'),fullPage:true})
  await page.screenshot({path:path.join(config.output,'desktop-viewport.png'),fullPage:false})
  const overflow=()=>page.evaluate(()=>({width:innerWidth,body:document.documentElement.scrollWidth}))
  assert.ok((await overflow()).body<=1586,'desktop overflow')
  await page.locator('.cm-segment button:nth-child(2)').click()
  await page.waitForSelector('.cm-overlay img:nth-child(2)')
  await page.locator('.cm-segment button:nth-child(3)').click()
  await page.waitForSelector('.cm-diff-image img')
  await page.locator('.cm-tabs button:nth-child(2)').click()
  await page.waitForFunction(()=>!!document.querySelector('.cm-code-block')?.textContent.includes('san.defineComponent'))
  await page.locator('.cm-tabs button:nth-child(3)').click()
  await page.waitForSelector('.cm-repair-timeline li')
  await page.locator('.cm-tabs button:nth-child(4)').click()
  await page.waitForSelector('.cm-artifact-list button')
  const target=await page.waitForSelector('.cm-artifact-list button');assert.ok(target)
  await page.locator('.cm-tabs button:nth-child(1)').click()
  await page.locator('.cm-sidebar > nav button:nth-child(2)').click()
  await page.waitForSelector('input[aria-label="搜索任务记录"]')
  await page.locator('input[aria-label="搜索任务记录"]').fill('HabitWeekTracker')
  await page.waitForFunction(()=>document.querySelectorAll('.cm-table tbody tr').length===1)
  await page.locator('input[aria-label="搜索任务记录"]').fill('no-such-component')
  await page.waitForFunction(()=>document.querySelector('.cm-records-page')?.textContent.includes('没有符合')||document.querySelector('.cm-table')?.parentElement?.parentElement?.textContent.includes('没有符合'))
  await page.locator('input[aria-label="搜索任务记录"]').click()
  await page.keyboard.down('Control');await page.keyboard.press('KeyA');await page.keyboard.up('Control');await page.keyboard.press('Backspace')
  await page.waitForFunction(()=>document.querySelectorAll('.cm-table tbody tr').length===5)
  assert.equal(await page.$$eval('.cm-sidebar > nav button',buttons=>buttons.length),2)
  assert.equal(await page.$eval('.cm-sidebar',e=>e.textContent.includes('实验对比')),false)
  await page.locator('button[aria-label="打开设置与连接"]').click()
  await page.waitForSelector('.cm-settings-grid')
  assert.equal((await page.$$('.cm-settings-grid input[type=password]')).length,0)
  await page.waitForFunction(()=>document.querySelector('.cm-settings-grid')?.textContent.includes('已自动连接'))
  await page.locator('.cm-settings-grid input[type=checkbox]').click()
  await page.screenshot({path:path.join(config.output,'settings.png'),fullPage:true})
  await page.locator('.cm-new-task').click()
  await page.waitForSelector('.cm-dialog[open]')
  assert.equal(await page.$eval('.cm-dialog button[type=submit]',b=>b.disabled),true)
  assert.equal((await page.$$('.cm-dialog input[type=checkbox]')).length,0)
  assert.equal((await page.$$('.cm-dialog input[type=password]')).length,0)
  assert.equal(await page.$eval('.cm-dialog input[aria-label="迁移策略"]',e=>e.value),'SSM ＋ 有界修复')
  assert.equal(await page.$$eval('.cm-dialog option',items=>items.some(e=>['direct','ssm_no_repair'].includes(e.value))),false)
  await page.screenshot({path:path.join(config.output,'create.png'),fullPage:true})
  await page.keyboard.press('Escape');await page.waitForFunction(()=>!document.querySelector('.cm-dialog'))
  await page.locator('.cm-sidebar > nav button:nth-child(1)').click()
  for(const width of [1024,390]){
    await page.setViewport({width,height:900,deviceScaleFactor:1})
    await new Promise(resolve=>setTimeout(resolve,150))
    const size=await overflow();assert.ok(size.body<=width,JSON.stringify(size))
    await page.screenshot({path:path.join(config.output,`width-${width}.png`),fullPage:true})
  }
  assert.deepEqual(errors,[]);assert.deepEqual(writes,[])
  console.log(JSON.stringify({status:'passed',page_errors:errors,write_requests:writes,viewports:[1586,1024,390],model_calls:0,checks:['real_report','screenshots_side_overlay_heatmap','accepted_code','repair_decisions','artifacts','search_empty_state','comparison_removed','user_ssm_strategy','no_confirmation_checkboxes','settings','modal_escape','responsive_no_horizontal_overflow']}))
}finally{await browser.close()}
